"""
LLaMA three-stage causal path patching.

Fixed functional positions:
    source   = role_adj_adv
    mediator = inst_all
    receiver = last

For each candidate chain:
    Role@source -> Instruction@mediator -> Last@receiver

Interventions
-------------
clean
corrupted

C1 source_patched
C2 source_patched + mediator_blocked

C3 clean_mediator_patched
C4 clean_mediator_patched + receiver_blocked

C5 source_induced_mediator_patched
C6 source_induced_mediator_patched + receiver_blocked

C7 source_patched + receiver_blocked

C5/C6 are the important full-chain test:
the mediator activation is first generated by actually patching the Role source
in the corrupted prompt, then that source-induced mediator state is transplanted
into a fresh corrupted run, with/without the Last receiver available.
"""

